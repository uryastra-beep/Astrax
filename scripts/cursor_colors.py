#!/usr/bin/env python3
"""Recolors the cursor (Bibata-Modern-Ice theme, via hyprcursor) based on the
primary color of the current song -- v2, after a performance audit.




Changes vs v1:
  A1 -- color threshold: only recolors if the new color is perceptibly
        different (redmean distance > COLOR_THRESHOLD). In v1, noise from the
        album art extractor (f9b6b1 -> f9b7a3, distance 20) triggered a
        full 30 s rebuild with all 4 cores at 100%.
        POLL_SECONDS 5 -> 15.
  A2 -- the theme is extracted ONCE to ~/.cache (disk), not to /tmp (tmpfs =
        RAM) on every pass. On low-RAM machines, writing hundreds of MB
        of PNGs to tmpfs was actively harmful.
  A2+ -- recoloring is done with numpy INSIDE this process instead of
        spawning ~2300 `magick` processes. Exact equivalent of the
        original chain: grey(Rec709) -> linear LUT black->color -> original alpha.
        From ~2300 forks down to ~190 (the ones hyprcursor-util spends internally).
"""

import json
import math
import os
import shutil
import subprocess
import time

import numpy as np
from PIL import Image

COLORS_FILE = "/tmp/widget-colors.json"
SOURCE_THEME = os.path.expanduser("~/.local/share/icons/Bibata-Modern-Ice")
ORIGINAL_THEME_NAME = "Bibata-Modern-Ice"
DYNAMIC_THEME_NAME = "Bibata-Dynamic"
DYNAMIC_THEME_DIR = os.path.expanduser(f"~/.local/share/icons/{DYNAMIC_THEME_NAME}")

CACHE_DIR = os.path.expanduser("~/.cache/cursor-colors")
PRISTINE_DIR = os.path.join(CACHE_DIR, "pristine")   # extracted theme, reused
WORK_DIR = os.path.join(CACHE_DIR, "work")           # working copy (disk)

CURSOR_SIZE = "24"
POLL_SECONDS = 15
COLOR_THRESHOLD = 30.0   # minimum redmean distance to justify a rebuild

_last_primary = None
_reverted = True


def get_primary_color():
    try:
        with open(COLORS_FILE) as f:
            return json.load(f).get("primary")
    except (FileNotFoundError, json.JSONDecodeError):
        return None


def _rgb(hex_color):
    h = hex_color.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def color_distance(a, b):
    """redmean -- a cheap and decent approximation of perceptual distance."""
    if a is None or b is None:
        return float("inf")
    try:
        r1, g1, b1 = _rgb(a)
        r2, g2, b2 = _rgb(b)
    except (ValueError, IndexError):
        return float("inf")
    rm = (r1 + r2) / 2.0
    dr, dg, db = r1 - r2, g1 - g2, b1 - b2
    return math.sqrt((2 + rm / 256) * dr * dr + 4 * dg * dg
                     + (2 + (255 - rm) / 256) * db * db)


def ensure_pristine():
    """Extracts the theme only once. If it's already cached, does nothing."""
    marker = os.path.join(PRISTINE_DIR, ".ok")
    if os.path.exists(marker):
        dirs = [d for d in os.listdir(PRISTINE_DIR) if d.startswith("extracted_")]
        if dirs:
            return os.path.join(PRISTINE_DIR, dirs[0])
    shutil.rmtree(PRISTINE_DIR, ignore_errors=True)
    os.makedirs(PRISTINE_DIR, exist_ok=True)
    subprocess.run(["hyprcursor-util", "--extract", SOURCE_THEME,
                    "--output", PRISTINE_DIR], check=True, capture_output=True)
    dirs = [d for d in os.listdir(PRISTINE_DIR) if d.startswith("extracted_")]
    if not dirs:
        raise RuntimeError("couldn't extract the cursor theme")
    open(marker, "w").close()
    return os.path.join(PRISTINE_DIR, dirs[0])


def build_lut(hex_color, path):
    """The LUT is generated by ImageMagick (1 fork per color change, not 2300).
    It isn't a linear ramp -- IM's resize filter adds overshoot
    (LUT[255] of #f9b7a3 is (255,196,174), not (249,183,163)) -- so
    reproducing it by hand would give a different color than v1. We generate it and
    index into it: identical result to v1, within 1/255."""
    subprocess.run(
        ["magick", "xc:black", f"xc:#{hex_color}", "+append",
         "-resize", "256x1!", path],
        check=True, capture_output=True,
    )
    return np.asarray(Image.open(path).convert("RGB"), dtype=np.uint8)[0]


def recolor_tree(root, hex_color, lut):
    """grey(Rec709) -> LUT -> original alpha. Equivalent to v1's
    ImageMagick chain, but in a single process and without forks."""
    n = 0
    for dirpath, _, files in os.walk(root):
        for name in files:
            if not name.endswith(".png"):
                continue
            path = os.path.join(dirpath, name)
            with Image.open(path) as im:
                arr = np.asarray(im.convert("RGBA"), dtype=np.float32)
            gray = (arr[..., 0] * 0.2126 + arr[..., 1] * 0.7152
                    + arr[..., 2] * 0.0722)
            idx = np.clip(np.rint(gray), 0, 255).astype(np.uint8)
            out = np.empty(arr.shape, dtype=np.uint8)
            out[..., :3] = lut[idx]
            out[..., 3] = arr[..., 3].astype(np.uint8)
            Image.fromarray(out, "RGBA").save(path)
            n += 1
    return n


def apply_color(hex_color):
    pristine = ensure_pristine()
    shutil.rmtree(WORK_DIR, ignore_errors=True)
    os.makedirs(WORK_DIR, exist_ok=True)
    work = os.path.join(WORK_DIR, os.path.basename(pristine))
    shutil.copytree(pristine, work)

    lut = build_lut(hex_color, os.path.join(WORK_DIR, "lut.png"))
    t0 = time.time()
    n = recolor_tree(work, hex_color, lut)
    t_recolor = time.time() - t0

    compiled_dir = os.path.join(WORK_DIR, "compiled")
    os.makedirs(compiled_dir, exist_ok=True)
    subprocess.run(["hyprcursor-util", "--create", work, "--output", compiled_dir],
                   check=True, capture_output=True)
    themes = [d for d in os.listdir(compiled_dir) if d.startswith("theme_")]
    if not themes:
        raise RuntimeError("couldn't compile the cursor theme")

    shutil.rmtree(DYNAMIC_THEME_DIR, ignore_errors=True)
    shutil.copytree(os.path.join(compiled_dir, themes[0]), DYNAMIC_THEME_DIR)
    subprocess.run(["hyprctl", "setcursor", DYNAMIC_THEME_NAME, CURSOR_SIZE],
                   check=True, capture_output=True)
    shutil.rmtree(WORK_DIR, ignore_errors=True)
    return n, t_recolor, time.time() - t0


def revert():
    subprocess.run(["hyprctl", "setcursor", ORIGINAL_THEME_NAME, CURSOR_SIZE],
                   check=True, capture_output=True)


def main():
    global _last_primary, _reverted
    while True:
        try:
            primary = get_primary_color()
            if primary is None:
                if not _reverted:
                    revert()
                    _reverted = True
                    _last_primary = None
                    print("cursor: reverted to the original", flush=True)
            else:
                dist = color_distance(primary, _last_primary)
                if dist > COLOR_THRESHOLD:
                    n, tr, tt = apply_color(primary)
                    _last_primary = primary
                    _reverted = False
                    print(f"cursor: recoloreado a {primary} "
                          f"({n} pngs, recolor {tr:.1f}s, total {tt:.1f}s, "
                          f"dist {dist:.0f})", flush=True)
                elif primary != _last_primary:
                    print(f"cursor: {primary} discarded, dist {dist:.0f} "
                          f"<= {COLOR_THRESHOLD:.0f} (noise)", flush=True)
                    _last_primary = primary
        except Exception as e:
            print(f"error: {e}", flush=True)
        time.sleep(POLL_SECONDS)


if __name__ == "__main__":
    main()
